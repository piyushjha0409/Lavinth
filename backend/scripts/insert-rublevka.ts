async function main() {
  let inserted = 0;
  let skipped = 0;

  for (const address of unattributed) {
    try {
      await pool.executeQuery(
        `INSERT INTO known_malicious_delegates (address, label, category, reported_losses, victim_count, first_reported_at, source, metadata, external_sources, confidence_score)
         VALUES ($1, $2, 'drainer', 0, 0, NOW(), 'recorded-future', $3, ARRAY['recorded-future'], 0.75)
         ON CONFLICT (address) DO UPDATE SET
           label = EXCLUDED.label,
           source = EXCLUDED.source,
           external_sources = EXCLUDED.external_sources,
           confidence_score = EXCLUDED.confidence_score,
           last_verified_at = NOW()`,
        [address, 'Rublevka Team drainer script address', JSON.stringify({ group: 'rublevka_team', role: 'drainer_script_address' })]
      );
      inserted++;
    } catch (e: any) {
      console.error(`Failed for ${address}: ${e.message}`);
      skipped++;
    }
  }

  console.log(`Inserted: ${inserted}, Skipped: ${skipped}`);

  // Update source total count
  const countResult = await pool.executeQuery(
    "SELECT COUNT(*) FROM known_malicious_delegates WHERE source = 'recorded-future'"
  );
  await pool.executeQuery(
    "UPDATE threat_intel_sources SET total_addresses = $1, last_sync_at = NOW() WHERE source_id = 'recorded-future'",
    [countResult.rows[0].count]
  );
  console.log(`Total Rublevka addresses in DB: ${countResult.rows[0].count}`);

  process.exit(0);
}

